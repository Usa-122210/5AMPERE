import { createContext, useContext, useState, useEffect, useMemo, useCallback } from 'react';
import { TARIFF_REGISTRY, DEFAULT_TARIFF_ID } from '../services/tariffData';
import { DEMO_HOUSEHOLD_METADATA, INITIAL_HOUSEHOLD_LOADS } from '../data/demoHouseholdData';
import {
  formatINR,
  wattsToKWh,
  calculateSlabCharge,
  getMarginalSlabRate,
  calculateMonthlyBill,
  calculatePeriodEstimate,
  calculateMarginalSavings,
  calculateHourlyCostEstimate,
  calculateCurrentEstimate,
  calculateApplianceCost,
} from '../utils/energyMath';
import { useAuth } from './AuthContext';

const EnergyDataContext = createContext(null);

export function EnergyDataProvider({ children }) {
  const { activeCustomerProperty } = useAuth();

  // Tariff selection and custom tariff state
  const [selectedTariffId, setSelectedTariffId] = useState(DEFAULT_TARIFF_ID);
  const [customTariff, setCustomTariff] = useState(TARIFF_REGISTRY['custom']);
  const [contractedLoadKw, setContractedLoadKw] = useState(
    activeCustomerProperty?.sanctionedLoadKw || DEMO_HOUSEHOLD_METADATA.contractedLoadKw
  );
  const [isTariffModalOpen, setIsTariffModalOpen] = useState(false);

  // Time range selection: 'today' | 'week' | 'month'
  const [timeRange, setTimeRange] = useState('today');

  // Connected appliances / circuit loads state
  const [loads, setLoads] = useState(INITIAL_HOUSEHOLD_LOADS);

  // Solar Rooftop simulated prototype state (defaults to inactive)
  const [solarEnabled, setSolarEnabled] = useState(false);
  const [solarPeakKw, setSolarPeakKw] = useState(2.0);

  // Dedicated Saving Mode state
  const [isSavingModeActive, setIsSavingModeActive] = useState(false);
  const [savingModeTargetPercent, setSavingModeTargetPercent] = useState(15);
  const [savingModeBudgetInr, setSavingModeBudgetInr] = useState(
    activeCustomerProperty?.approxMonthlyBill || 4500
  );

  // Sync sanctioned load & budget when customer switches property persona
  useEffect(() => {
    if (activeCustomerProperty) {
      if (activeCustomerProperty.sanctionedLoadKw) {
        setContractedLoadKw(Number(activeCustomerProperty.sanctionedLoadKw));
      }
      if (activeCustomerProperty.approxMonthlyBill) {
        setSavingModeBudgetInr(Number(activeCustomerProperty.approxMonthlyBill));
      }
    }
  }, [activeCustomerProperty?.id]);

  // Safety Confirmation Modal state
  const [confirmationModal, setConfirmationModal] = useState({
    isOpen: false,
    title: '',
    message: '',
    isDangerous: false,
    confirmLabel: 'Confirm Action',
    onConfirm: null,
  });

  const closeConfirmationModal = useCallback(() => {
    setConfirmationModal((prev) => ({ ...prev, isOpen: false }));
  }, []);

  // Alerts state
  const [alerts, setAlerts] = useState([
    {
      id: 'alert-1',
      severity: 'warning',
      title: 'High Evening Peak Draw Detected',
      message: 'Active load reached 2.65 kW at 20:00 (53% of 5.0 kW Sanctioned Load). Simultaneous cooling and water heating active.',
      timestamp: 'Today, 20:15',
      circuitId: 'ac',
      acknowledged: false,
    },
    {
      id: 'alert-2',
      severity: 'info',
      title: 'Continuous 95W Standby Power Observation',
      message: 'Entertainment cluster drawing 95W phantom power during idle night hours (00:30–06:00).',
      timestamp: 'Today, 03:00',
      circuitId: 'entertainment',
      acknowledged: false,
    },
    {
      id: 'alert-3',
      severity: 'info',
      title: 'Demonstration Telemetry Mode Active',
      message: 'Current readings are generated by the calibrated local simulation model. Physical sensor telemetry is pending hardware connection.',
      timestamp: 'System Initialization',
      circuitId: null,
      acknowledged: false,
    },
  ]);

  const dismissAlert = useCallback((alertId) => {
    setAlerts((prev) => prev.filter((a) => a.id !== alertId));
  }, []);

  // Resolve active tariff
  const activeTariff = useMemo(() => {
    if (selectedTariffId === 'custom') {
      return customTariff;
    }
    return TARIFF_REGISTRY[selectedTariffId] || TARIFF_REGISTRY[DEFAULT_TARIFF_ID];
  }, [selectedTariffId, customTariff]);

  // Update custom tariff configuration
  const updateCustomTariff = useCallback((newConfig) => {
    setCustomTariff((prev) => ({ ...prev, ...newConfig }));
  }, []);

  // Internal direct toggle
  const executeToggleLoad = useCallback((loadId) => {
    setLoads((prev) =>
      prev.map((item) => (item.id === loadId ? { ...item, active: !item.active } : item))
    );
  }, []);

  // Safe Load Relay Toggle Request (Checks for Critical circuit protection)
  const requestRelayToggle = useCallback((loadId) => {
    const targetLoad = loads.find((l) => l.id === loadId);
    if (!targetLoad) return;

    if (targetLoad.priority === 'Critical') {
      setConfirmationModal({
        isOpen: true,
        title: `Caution: Protected Circuit (${targetLoad.name})`,
        message: `${targetLoad.name} is classified as a Critical circuit (${targetLoad.category}). Switching this off may interrupt vital refrigeration or security. Are you sure you want to open this contactor relay?`,
        isDangerous: true,
        confirmLabel: targetLoad.active ? 'Shed Critical Circuit' : 'Restore Circuit',
        onConfirm: () => {
          executeToggleLoad(loadId);
          closeConfirmationModal();
        },
      });
    } else {
      setConfirmationModal({
        isOpen: true,
        title: `Confirm Relay Action — ${targetLoad.name}`,
        message: `Simulate switching contactor relay for ${targetLoad.name} ${targetLoad.active ? 'OFF' : 'ON'}? (Active draw: ${targetLoad.drawKw.toFixed(2)} kW).`,
        isDangerous: false,
        confirmLabel: targetLoad.active ? 'Turn Relay OFF' : 'Turn Relay ON',
        onConfirm: () => {
          executeToggleLoad(loadId);
          closeConfirmationModal();
        },
      });
    }
  }, [loads, executeToggleLoad, closeConfirmationModal]);

  // Shed heavy / discretionary loads with confirmation
  const requestShedHeavyLoads = useCallback(() => {
    setConfirmationModal({
      isOpen: true,
      title: 'Confirm Automated Load Shedding',
      message: 'This action will simulate shedding discretionary loads (EV Wallbox, Water Geyser) to reduce active household demand. Critical circuits (Refrigerator) will remain protected. Proceed?',
      isDangerous: false,
      confirmLabel: 'Execute Load Shedding',
      onConfirm: () => {
        setLoads((prev) =>
          prev.map((item) => {
            if (item.priority === 'Discretionary' || item.id === 'geyser' || item.id === 'ev') {
              return { ...item, active: false };
            }
            return item;
          })
        );
        closeConfirmationModal();
      },
    });
  }, [closeConfirmationModal]);

  // Restore all circuits
  const restoreAllLoads = useCallback(() => {
    setLoads((prev) => prev.map((item) => ({ ...item, active: true })));
  }, []);

  // Toggle Saving Mode with simulation action
  const toggleSavingMode = useCallback((explicitState) => {
    setIsSavingModeActive((prev) => {
      const next = explicitState !== undefined ? explicitState : !prev;
      if (next) {
        // Automatically shed discretionary loads in simulation
        setLoads((current) =>
          current.map((item) => {
            if (item.priority === 'Discretionary' || item.id === 'geyser') {
              return { ...item, active: false };
            }
            return item;
          })
        );
      }
      return next;
    });
  }, []);

  // Active load summary
  const totalActiveWatts = useMemo(() => {
    return Math.round(
      loads.reduce((sum, item) => (item.active ? sum + item.drawKw * 1000 : sum), 0)
    );
  }, [loads]);

  const totalActiveKw = useMemo(() => {
    return Math.round((totalActiveWatts / 1000) * 100) / 100;
  }, [totalActiveWatts]);

  // Estimated Current in Amps using active watts, 230V nominal, and PF 0.95
  const currentAmps = useMemo(() => {
    return calculateCurrentEstimate(totalActiveWatts, DEMO_HOUSEHOLD_METADATA.nominalVoltage, 0.95);
  }, [totalActiveWatts]);

  const activeLoadCount = useMemo(() => {
    return loads.filter((l) => l.active).length;
  }, [loads]);

  // Nominal active load benchmark (~2.11 kW when AC, Fridge, Fans, TV are active)
  const nominalActiveKw = 2.11;
  const loadDeltaKw = totalActiveKw - nominalActiveKw;

  // Calibrated simulation model for daily consumption:
  // Base daily is ~24.5 kWh for typical Indian 3BHK home with AC.
  const dailyKwh = useMemo(() => {
    const baseline = 24.5;
    const computed = baseline + loadDeltaKw * 5; // 5 equivalent full-load hours of modulation
    return Math.max(3.0, Math.round(computed * 10) / 10);
  }, [loadDeltaKw]);

  const weeklyKwh = useMemo(() => {
    return Math.round(dailyKwh * 7 * 10) / 10;
  }, [dailyKwh]);

  // Projected 30-day cumulative billing cycle consumption (kWh)
  const projectedBillingCycleKwh = useMemo(() => {
    return Math.round(dailyKwh * 30 * 10) / 10;
  }, [dailyKwh]);

  // Selected period consumption
  const selectedPeriodKwh = useMemo(() => {
    if (timeRange === 'today') return dailyKwh;
    if (timeRange === 'week') return weeklyKwh;
    return projectedBillingCycleKwh;
  }, [timeRange, dailyKwh, weeklyKwh, projectedBillingCycleKwh]);

  // 1. Official 30-day projected billing cycle bill
  const projectedMonthlyBill = useMemo(() => {
    return calculateMonthlyBill(projectedBillingCycleKwh, activeTariff, contractedLoadKw);
  }, [projectedBillingCycleKwh, activeTariff, contractedLoadKw]);

  // 2. Selected period cost estimate (daily, weekly, or full monthly bill)
  const periodEstimate = useMemo(() => {
    return calculatePeriodEstimate(
      selectedPeriodKwh,
      projectedBillingCycleKwh,
      activeTariff,
      contractedLoadKw,
      timeRange
    );
  }, [selectedPeriodKwh, projectedBillingCycleKwh, activeTariff, contractedLoadKw, timeRange]);

  // Hourly cost estimation (marginal energy charge for instantaneous draw)
  const hourlyCost = useMemo(() => {
    return calculateHourlyCostEstimate(totalActiveWatts, activeTariff, projectedBillingCycleKwh);
  }, [totalActiveWatts, activeTariff, projectedBillingCycleKwh]);

  // Enhanced loads with individual daily/monthly costs
  const loadsWithCosts = useMemo(() => {
    return loads.map((item) => {
      const costData = calculateApplianceCost(
        item.drawKw,
        item.dailyRunHours || 4,
        periodEstimate.effectiveEnergyRate
      );
      return {
        ...item,
        ...costData,
      };
    });
  }, [loads, periodEstimate.effectiveEnergyRate]);

  // Solar simulated prototype calculations
  const solarKw = useMemo(() => {
    return solarEnabled ? solarPeakKw * 0.75 : 0.0;
  }, [solarEnabled, solarPeakKw]);

  const gridKw = useMemo(() => {
    return Math.max(0, Math.round((totalActiveKw - solarKw) * 100) / 100);
  }, [totalActiveKw, solarKw]);

  const selfSufficiency = useMemo(() => {
    if (totalActiveKw <= 0) return 0;
    return Math.min(100, Math.round((solarKw / totalActiveKw) * 100));
  }, [solarKw, totalActiveKw]);

  // Backward-compatible alias for rangeBillBreakdown
  const rangeBillBreakdown = useMemo(() => {
    return {
      ...periodEstimate,
      totalBill: periodEstimate.allocatedTotal,
      effectiveRatePerKWh: periodEstimate.effectiveEnergyRate,
    };
  }, [periodEstimate]);

  // Value context payload
  const value = {
    // Metadata
    metadata: DEMO_HOUSEHOLD_METADATA,

    // Tariffs
    tariffs: TARIFF_REGISTRY,
    selectedTariffId,
    setSelectedTariffId,
    customTariff,
    updateCustomTariff,
    activeTariff,
    isTariffVerified: activeTariff.verified === true,
    contractedLoadKw,
    setContractedLoadKw,

    // Modal
    isTariffModalOpen,
    openTariffModal: () => setIsTariffModalOpen(true),
    closeTariffModal: () => setIsTariffModalOpen(false),

    // Confirmation Modal
    confirmationModal,
    closeConfirmationModal,

    // Loads
    loads,
    loadsWithCosts,
    toggleLoad: executeToggleLoad,
    requestRelayToggle,
    shedPeakLoads: requestShedHeavyLoads,
    restoreAllLoads,
    totalActiveWatts,
    totalActiveKw,
    currentAmps,
    activeLoadCount,

    // Time window
    timeRange,
    setTimeRange,

    // Saving Mode
    isSavingModeActive,
    toggleSavingMode,
    savingModeTargetPercent,
    setSavingModeTargetPercent,
    savingModeBudgetInr,
    setSavingModeBudgetInr,

    // Alerts
    alerts,
    dismissAlert,
    unreadAlertCount: alerts.length,

    // Solar simulated prototype
    solarEnabled,
    setSolarEnabled,
    solarPeakKw,
    setSolarPeakKw,
    solarKw,
    gridKw,
    selfSufficiency,

    // Consumption metrics
    dailyKwh,
    weeklyKwh,
    projectedBillingCycleKwh,
    selectedPeriodKwh,
    selectedKwh: selectedPeriodKwh, // alias

    // Billing calculations
    projectedMonthlyBill,
    monthlyProjection: projectedMonthlyBill, // alias
    periodEstimate,
    rangeBillBreakdown, // alias
    hourlyCost,

    // Utilities
    formatINR,
    wattsToKWh,
    calculateSlabCharge,
    getMarginalSlabRate,
    calculateMonthlyBill,
    calculatePeriodEstimate,
    calculateMarginalSavings,
    calculateApplianceCost,
  };

  return <EnergyDataContext.Provider value={value}>{children}</EnergyDataContext.Provider>;
}

export function useEnergyData() {
  const context = useContext(EnergyDataContext);
  if (!context) {
    throw new Error('useEnergyData must be used within an EnergyDataProvider');
  }
  return context;
}
